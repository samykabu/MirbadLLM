    public string? NewSpkiSha256 { get; init; }

    /// <summary>Expiry of the newly issued certificate.</summary>
    public DateTimeOffset? NewCertNotAfter { get; init; }

    /// <summary>When the rotation started.</summary>
    public DateTimeOffset StartedAt { get; init; }

    /// <summary>When the stage last changed.</summary>
    public DateTimeOffset UpdatedAt { get; init; }

    /// <summary>Last error, for the Nodes page. Null when none.</summary>
    public string? Error { get; init; }
}

