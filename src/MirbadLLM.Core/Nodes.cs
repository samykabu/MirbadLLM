namespace MirbadLLM.Core;

/// <summary>
/// Serializer options for the master's multi-node state files (<c>nodes.json</c>, <c>master.json</c>; design §5.3,
/// §4.2): web defaults (camelCase), camelCase string enums, indented, nulls written. Read-only.
/// </summary>
public static class MasterStateJson
{
    /// <summary>The shared, read-only options.</summary>
    public static JsonSerializerOptions Options { get; } = Create();

    private static JsonSerializerOptions Create()
    {
        var options = new JsonSerializerOptions(JsonSerializerDefaults.Web)
        {
            WriteIndented = true,
            Converters = { new JsonStringEnumConverter(JsonNamingPolicy.CamelCase) },
        };
        options.MakeReadOnly(populateMissingResolver: true);
        return options;
    }
}

/// <summary>
/// A node's state on the master (design §3.5). <see cref="NodeRecord.Draining"/> is a separate flag, so a draining node
/// can also be Offline. Serialized camelCase (<c>pendingApproval</c>, <c>online</c>, …).
/// </summary>
public enum NodeState
{
    /// <summary>Enrolled, not yet approved: only <c>info</c> is called, nothing is placed there.</summary>
    PendingApproval,

    /// <summary>Reachable, protocol negotiated, all checks pass.</summary>
    Online,

    /// <summary>Reachable but a subsystem is failing (reasons listed); commands needing it fail with a clear reason.</summary>
    Degraded,

    /// <summary><c>/info</c> answers but no protocol version overlaps: blocked for routing, auto-start and commands (§3.6).</summary>
    Incompatible,

    /// <summary>No contact for 15 s (3 missed heartbeats).</summary>
    Offline,

    /// <summary>Unreachable during a fencing takeover; blocked until its accepted epoch is below the master's (§4.2, P2).</summary>
    PendingTakeover,

    /// <summary>Removed: pins deleted, the master refuses connections.</summary>
    Revoked,
}

/// <summary>
/// One node in <c>nodes.json</c> (design §5.3). Holds identity, trust (SPKI pins), operator settings and the last
/// capability report. Never holds secrets: pins are public-key hashes.
/// </summary>
public sealed record NodeRecord
{
    /// <summary>Node id slug <c>^[a-z0-9][a-z0-9-]{0,39}$</c> (design §3.1); immutable.</summary>
    public required string Id { get; init; }

    /// <summary>Random 128-bit id generated by the master at enrollment, stored on both sides (hex).</summary>
    public required string Uid { get; init; }

    /// <summary>Display name. Null = the id.</summary>
    public string? DisplayName { get; init; }

    /// <summary>Agent base address, e.g. <c>https://127.0.0.1:9443</c>.</summary>
    public required string Address { get; init; }

    /// <summary>Other addresses of the agent (tried in order when <see cref="Address"/> fails).</summary>
    public IReadOnlyList<string> AltAddresses { get; init; } = [];

    /// <summary>True once the operator approved the node (the bootstrap node is pre-approved).</summary>
    public bool Approved { get; init; }

    /// <summary>Operator flag: no new starts or placements; running models keep serving.</summary>
    public bool Draining { get; init; }

    /// <summary>True after revoke; the record is kept so its id and uid are not silently reused.</summary>
    public bool Revoked { get; init; }

    /// <summary>Base64 SHA-256 of the agent certificate's SubjectPublicKeyInfo: the pin (design §3.1). Null until enrolled.</summary>
    public string? CertSpkiSha256 { get; init; }

    /// <summary>
    /// Pending pin: the enrolled key before approval, or the new key during a two-phase rotation (design §10.2 step 2).
    /// While set, the master accepts either pin for this node.
    /// </summary>
    public string? PendingCertSpkiSha256 { get; init; }

    /// <summary>Expiry of the current agent certificate.</summary>
    public DateTimeOffset? CertNotAfter { get; init; }

    /// <summary>Memory kept free on this node when admitting a model (replaces the global reserve per node, §5.3).</summary>
    public double MemoryReserveGiB { get; init; } = 8;

    /// <summary>
    /// The reserve a newly enrolled node starts with: an eighth of its memory, between 1 and 8 GiB (8 GiB on the DGX and a
    /// 64 GiB PC, 1 GiB on an 8 GiB Mac, where a flat 8 GiB left nothing for a model). 8 when the size is unknown.
    /// </summary>
    public static double DefaultMemoryReserveGiB(double? totalGiB) =>
        totalGiB is double total and > 0 ? Math.Clamp(Math.Round(total / 8, 1), 1, 8) : 8;

    /// <summary>Per-GPU reserve by GPU UUID (discrete nodes, P2). Empty = none.</summary>
    public IReadOnlyDictionary<string, double> GpuReserveGiB { get; init; } = new Dictionary<string, double>();

    /// <summary>Concurrent starts allowed (§4.8). Null = the default (unified: 1; discrete: one per GPU).</summary>
    public int? MaxConcurrentStarts { get; init; }

    /// <summary>Node default vLLM image. Null = <see cref="MirbadLLMOptions.VllmImage"/> (the DGX keeps today's fallback, §5.1).</summary>
    public string? DefaultVllmImage { get; init; }

    /// <summary>
    /// Approved repository digest (<c>sha256:…</c>) of <see cref="DefaultVllmImage"/> (design §10.3, §12.1 Settings; MN-107,
    /// D73). Sent as <c>spec.imageDigest</c> when the model has no image of its own. Null = none (the DGX keeps today's tag
    /// fallback, so its legacy hash is unchanged). Omitted from <c>nodes.json</c> when null.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? DefaultVllmImageDigest { get; init; }

    /// <summary>Node default llama.cpp image (P3; stored from P2 so the Settings tab has one shape). Omitted when null.</summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? DefaultLlamaCppImage { get; init; }

    /// <summary>Approved digest of <see cref="DefaultLlamaCppImage"/>. Omitted when null.</summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? DefaultLlamaCppImageDigest { get; init; }

    /// <summary>Free-form labels, e.g. <c>arm64</c>, <c>gb10</c>.</summary>
    public IReadOnlyList<string> Labels { get; init; } = [];

    /// <summary>Last capability report, so an Offline node's hardware stays visible.</summary>
    public NodeCapabilities? LastCapabilities { get; init; }

    /// <summary>Time of the last event or successful call.</summary>
    public DateTimeOffset? LastContact { get; init; }

    /// <summary>When the record was created.</summary>
    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>When the node enrolled (certificate issued).</summary>
    public DateTimeOffset? EnrolledAt { get; init; }

    /// <summary>Source address of the enroll request, shown in the approval dialog (design §3.2).</summary>
    public string? EnrolledFrom { get; init; }

    /// <summary>When the operator approved the node.</summary>
    public DateTimeOffset? ApprovedAt { get; init; }

    /// <summary>When the node was revoked.</summary>
    public DateTimeOffset? RevokedAt { get; init; }

    /// <summary>The open (or last) agent-certificate rotation (design §10.2). Null = none yet.</summary>
    public CertificateRotationRecord? Rotation { get; init; }
}

/// <summary>Why a join token was created (design §3.2).</summary>
public enum JoinTokenPurpose
{
    /// <summary>Created by an operator for "Add node" (P2), shown once.</summary>
    Join,

    /// <summary>Written into the DGX bootstrap bundle (P1).</summary>
    Bootstrap,

    /// <summary>
    /// Created by an operator to re-pair an <b>enrolled</b> node with <c>join --rekey</c> (P2, MN-102 creates, MN-114
    /// consumes at <c>/enroll/rekey</c>; design §9.4 step 5, D73). Valid only for that route: <c>/enroll</c> refuses it, and
    /// a join or bootstrap token is refused by <c>/enroll/rekey</c>. Written as <c>rekey</c>; a P1 master cannot read a
    /// <c>nodes.json</c> that still lists one (downgrade rule in D73).
    /// </summary>
    Rekey,
}

/// <summary>
/// A join token in <c>nodes.json</c> (design §3.2, §5.3): only the SHA-256 of the token is stored, bound to one node id,
/// with an expiry, and marked used (persisted) before any certificate is issued.
/// </summary>
public sealed record JoinTokenRecord
{
    /// <summary>Base64url SHA-256 of the token's UTF-8 bytes.</summary>
    public required string Sha256 { get; init; }

    /// <summary>The node id the token may enroll.</summary>
    public required string NodeId { get; init; }

    /// <summary>When the token was created.</summary>
    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>When the token stops working (default TTL 60 min, 10 min – 24 h).</summary>
    public required DateTimeOffset ExpiresAt { get; init; }

    /// <summary>When the token was consumed. A used token never works again.</summary>
    public DateTimeOffset? UsedAt { get; init; }

    /// <summary>Operator join or bootstrap bundle.</summary>
    public JoinTokenPurpose Purpose { get; init; }
}

/// <summary>Master-side stage of an agent-certificate rotation (design §10.2). Persisted before each step it names.</summary>
public enum CertificateRotationStage
{
    /// <summary>Record written; <c>POST /pki/rotations</c> may have been sent.</summary>
    Requested,

    /// <summary>The agent returned a CSR.</summary>
    CsrReceived,

    /// <summary>The master signed it and stored the new SPKI as the pending pin.</summary>
    CertIssued,

    /// <summary><c>PUT /pki/rotations/{id}/cert</c> succeeded; the agent presents the new certificate on new connections.</summary>
    CertInstalled,

    /// <summary>Persisted before sending <c>commit</c>: from here on, abort is no longer allowed.</summary>
    Committing,

    /// <summary>The agent committed; the pending pin was promoted and both handlers replaced.</summary>
    Committed,

    /// <summary>Aborted before commit; both sides keep the old material.</summary>
    Aborted,
}

/// <summary>An agent-certificate rotation record, stored on its <see cref="NodeRecord"/> (design §10.2 step 1).</summary>
