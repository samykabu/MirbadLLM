/// <summary>
/// Lifecycle of an agent operation (design §4.3, §4.4). Terminal: Succeeded, Failed, Cancelled, Unknown. <c>Unknown</c>
/// means a host-service action was dispatched but its outcome could not be verified after a crash or timeout (§4.4
/// item 8); nothing is replayed. Serialized camelCase on the wire.
/// </summary>
public enum OperationState
{
    /// <summary>Durably accepted, not running yet.</summary>
    Accepted,

    /// <summary>Running.</summary>
    Running,

    /// <summary>Finished successfully.</summary>
    Succeeded,

    /// <summary>Finished with an error.</summary>
    Failed,

    /// <summary>Cancelled by a cancel operation.</summary>
    Cancelled,

    /// <summary>Outcome could not be verified; the UI asks the operator to check and act again.</summary>
    Unknown,
}

/// <summary>Helpers for <see cref="OperationState"/>.</summary>
public static class OperationStateExtensions
{
    /// <summary>True for Succeeded, Failed, Cancelled and Unknown.</summary>
    public static bool IsTerminal(this OperationState state) =>
        state is OperationState.Succeeded or OperationState.Failed or OperationState.Cancelled or OperationState.Unknown;
}

