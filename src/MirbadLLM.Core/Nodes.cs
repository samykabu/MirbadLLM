/// <summary>
/// The master's runtime status cache (design §3.4–3.6, §4.7, §7.1), implemented by
/// <c>MirbadLLM.Orchestration.Nodes.NodeStatusCache</c> and fed by <c>NodeMonitor</c> (MN-027).
/// <para>Invariants: reads never call an agent (the router reads it per request); a snapshot is applied before the
/// event stream resumes from its <c>seq</c>, and events with <c>seq ≤</c> the last applied for the same boot are
/// ignored; a node with no contact for 15 s is Offline; every view is immutable (readers get a consistent copy).</para>
/// </summary>
public interface INodeStatusCache
{
    /// <summary>Incremented on every change; pages poll it to decide whether to re-render.</summary>
    long Version { get; }

    /// <summary>Every known node (revoked ones excluded).</summary>
    IReadOnlyList<NodeLiveStatus> ListNodes();

    /// <summary>One node, or null when unknown.</summary>
    NodeLiveStatus? GetNode(string nodeId);

    /// <summary>The instance of a model on its node, or null when the node reports none (Stopped) or is unknown.</summary>
    NodeModelRuntime? GetRuntime(string modelId);

    /// <summary>Instances on one node, or on all nodes when <paramref name="nodeId"/> is null.</summary>
    IReadOnlyList<NodeModelRuntime> ListRuntimes(string? nodeId = null);

    /// <summary>
    /// Resolves a served model name to its model, node and states (design §7.1). Null when no placed model has that
    /// served name (the router answers 404 <c>model_not_found</c>; unplaced models are the router's own check).
    /// </summary>
    ServedModelRoute? ResolveServedName(string servedName);

