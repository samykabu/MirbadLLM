/// <summary>Outcome of consuming a join token (design §3.2).</summary>
public enum JoinTokenConsumeOutcome
{
    /// <summary>Valid; marked used and persisted before returning.</summary>
    Consumed,

    /// <summary>No token with that hash.</summary>
    Unknown,

    /// <summary>Past its expiry.</summary>
    Expired,

    /// <summary>Already used.</summary>
    AlreadyUsed,

    /// <summary>Bound to another node id.</summary>
    WrongNode,

    /// <summary>The node the token is bound to has been revoked (added by MN-090); the token stays unused.</summary>
    NodeRevoked,
