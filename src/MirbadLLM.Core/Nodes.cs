/// <summary>
/// Persistent store of nodes and join tokens (<c>nodes.json</c>, design §5.3), implemented by
/// <c>MirbadLLM.Orchestration.Nodes.JsonNodeRegistry</c> (MN-005). Sibling of <see cref="IModelRegistry"/>.
/// <para>Invariants: every write is atomic (temp file + move) under one semaphore; join tokens are stored as SHA-256
/// hashes only; a token is consumed at most once, and its consumption is persisted before the call returns; revoked nodes
/// are kept with the flag.</para>
/// </summary>
public interface INodeRegistry
{
    /// <summary>Every node, revoked ones included.</summary>
    Task<IReadOnlyList<NodeRecord>> ListAsync(CancellationToken ct = default);

    /// <summary>The node with this id, or null.</summary>
    Task<NodeRecord?> GetAsync(string id, CancellationToken ct = default);

    /// <summary>Adds or replaces a node record.</summary>
    Task UpsertAsync(NodeRecord node, CancellationToken ct = default);

    /// <summary>
    /// Atomic read-modify-write of one node under the registry lock (rotation stages, pins, last contact). Returns the
    /// stored result, or null when the node does not exist (<paramref name="update"/> is then not called).
    /// </summary>
    Task<NodeRecord?> UpdateAsync(string id, Func<NodeRecord, NodeRecord> update, CancellationToken ct = default);

    /// <summary>Marks the node revoked and deletes its pins (current and pending). False when it does not exist.</summary>
    Task<bool> RevokeAsync(string id, CancellationToken ct = default);

    /// <summary>Removes the record entirely (reject of a pending node, design §3.2). False when it does not exist.</summary>
    Task<bool> DeleteAsync(string id, CancellationToken ct = default);

    /// <summary>
    /// Creates a join token for <paramref name="nodeId"/> valid for <paramref name="lifetime"/>. The plaintext is in the
    /// result only; <c>nodes.json</c> keeps the hash.
    /// </summary>
    Task<JoinTokenIssue> CreateJoinTokenAsync(string nodeId, TimeSpan lifetime, JoinTokenPurpose purpose, CancellationToken ct = default);

    /// <summary>
    /// Consumes <paramref name="token"/> for <paramref name="nodeId"/> under the registry lock: constant-time hash
    /// comparison, unexpired, unused, bound to that node. On success the token is marked used and persisted before
    /// returning, so concurrent callers with one token succeed exactly once.
    /// </summary>
    Task<JoinTokenConsumption> TryConsumeJoinTokenAsync(string token, string nodeId, CancellationToken ct = default);

    /// <summary>Join token records (hashes only), for the UI.</summary>
    Task<IReadOnlyList<JoinTokenRecord>> ListJoinTokensAsync(CancellationToken ct = default);

    /// <summary>
    /// Expires every unused, unexpired join token bound to <paramref name="nodeId"/> (sets its <c>ExpiresAt</c> to now, in
    /// one locked write) and returns how many it expired (P2, MN-102: an operator "revoke token" action, and the bootstrap
    /// bundle rewrite of the W3 review MN-094). Expiring rather than flagging keeps the record readable by a P1 master.
    /// <para>Stub until MN-102 implements it in <c>JsonNodeRegistry</c>: the default throws
    /// <see cref="NotSupportedException"/>.</para>
    /// </summary>
    Task<int> ExpireUnusedJoinTokensAsync(string nodeId, CancellationToken ct = default) =>
        throw new NotSupportedException("ExpireUnusedJoinTokensAsync is implemented by MN-102 (JsonNodeRegistry).");

    /// <summary>
    /// Removes used or expired join token records whose <c>UsedAt</c> (or <c>ExpiresAt</c>) is older than
    /// <paramref name="olderThan"/> and returns how many it removed (P2, MN-102, W1 review MN-090 "prune after N days").
    /// <para>Stub until MN-102: the default throws <see cref="NotSupportedException"/>.</para>
    /// </summary>
    Task<int> PruneJoinTokensAsync(TimeSpan olderThan, CancellationToken ct = default) =>
        throw new NotSupportedException("PruneJoinTokensAsync is implemented by MN-102 (JsonNodeRegistry).");
}

